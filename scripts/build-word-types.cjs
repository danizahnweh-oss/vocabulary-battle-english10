/* Explicit exceptions plus source grammar cues; emits stable, reviewable tags.
   This runs when vocabulary is updated, never guesses during a question. */
const fs=require('node:fs'),vm=require('node:vm');
const root=require('node:path').resolve(__dirname,'..');
const set=s=>new Set(s.split('|'));
const exceptions={
 noun:set('self|in-crowd|the Pope|Spanish Armada|my fault|good luck|a while|guided tour|Welsh rarebit|public holiday|diner|running water|local news|the news|social media|the Welsh dragon|Welsh castle|early colonial history|junior high school|high school|secondary school|sixth grade|Year 6|drastic change|ethnic background|virtual reality|public transit|multinational company|civil disobedience|freelance work|fossil fuel|leak|parliamentary democracy|sanitation|glimpse|renewable energy|evil|global village|ethnicity|liquor|gentry|layer of'),
 adjective:set('environmental|residential|coastal|corporate|external|deputy|Tudor|out of focus|out of breath|hardest hit|densely populated|ethnically diverse|wooden|daily|abundant'),
 adverb:set('all by oneself|this way|the most|far away|this|that|a day|mostly|especially|underground|perhaps|definitely|in power|next door|back then|more and more|last night|not even|overboard|on board|tonight|at one’s own risk|however|quite|therefore|off|normally|particularly|worldwide|vastly|uptown|in return|on foot|approximately|primarily|utterly|in … terms|immediately|solely|abroad|overall|overseas|virtually|in times of trouble|in the 16th century|in the Elizabethan Age|in the Victorian Age|under Spanish rule|during the reign of Queen Victoria'),
 pronoun:set('themselves|anything|they|so'),
 preposition:set('in sb’s shoes|according to|since|for|above|within|on the brink of|among|apart from|by|in comparison with/to|in close proximity|prior to|beyond|for fear of'),
 conjunction:set('as long as|either … or …|as|as if|even though|once'),
 determiner:set('some|such|little'),
 numeral:set('fifteen'),
 phrase:set('I don’t care|I don’t mind|What’s going on?|What’s wrong?|Cheers!|what for'),
 verb:set('could|take to the streets|be a driver')
};
function base(en){return en.replace(/\s*\([^)]*\)/g,'').trim();}
function classify(w){
 const en=base(w.en);
 if(/^to\s/.test(en))return 'verb';
 for(const [pos,words] of Object.entries(exceptions))if(words.has(en))return pos;
 if(/\(adjective\)/.test(w.en))return 'adjective';
 if(/\(noun\)/.test(w.en))return 'noun';
 // A German noun phrase may begin with an adjective (e.g. "sanitäre Anlagen").
 // Capitalised prefixes ending in a hyphen (e.g. "Finanz-") modify a noun.
 const meaning=w.de.split(';')[0].replace(/\([^)]*\)/g,'');
 return /(?<![\p{L}])[A-ZÄÖÜ][\p{L}/-]*/u.test(meaning)?'noun':'adjective';
}
const result={},report=[];
for(const grade of [7,10,11]){
 const context=vm.createContext({});
 for(const file of grade===7?['7/vocabulary-additions.js','7/vocabulary.js']:[`${grade}/vocabulary.js`])vm.runInContext(fs.readFileSync(root+'/'+file,'utf8'),context);
 const words=vm.runInContext('JSON.parse(JSON.stringify(VOCAB))',context);
 result[grade]={};
 for(const w of words){const pos=classify(w);const senses=w.de.split(';').map(s=>s.trim());
  const nounSense=s=>/(?<![\p{L}])[A-ZÄÖÜ][\p{L}/-]*/u.test(s.replace(/\([^)]*\)/g,'').replace(/[A-ZÄÖÜ][\p{L}]*-(?=\s|$)/gu,''));
  const adjectiveSense=s=>!/^\s*[A-ZÄÖÜ]/u.test(s)||/-$/.test(s);
  const filtered=pos==='noun'?senses.filter(nounSense):pos==='adjective'?senses.filter(adjectiveSense):senses;
  result[grade][w.id]=[pos,(filtered.length?filtered:senses).join('; ')];report.push([grade,w.id,pos,w.en,w.de].join('\t'));}
 console.log(`Grade ${grade}: ${words.length} words`,Object.fromEntries([...new Set(Object.values(result[grade]).map(v=>v[0]))].map(pos=>[pos,Object.values(result[grade]).filter(p=>p[0]===pos).length])));
}
fs.writeFileSync(root+'/shared/word-types.js',`/* Generated by scripts/build-word-types.cjs. Keep tags in sync with vocabulary. */\nconst WORD_TYPES=${JSON.stringify(result,null,1)};\n`);
fs.writeFileSync('/tmp/vocab-word-types.tsv','grade\tid\tpartOfSpeech\tEnglish\tGerman\n'+report.join('\n')+'\n');
